# ============================
# 1. 最简单的输出
# ============================
print("Hello, World!")
print("你好，世界！")
print("我正在学习 Python！")

# ============================
# 2. print() 的多种用法
# ============================
print()  # 空的 print() 输出一个空行

# 显示数字
print(42)
print(3.14)

# 显示计算结果
print("1 + 1 =", 1 + 1)
print("10 * 3 =", 10 * 3)

# 多个内容用逗号分隔
print("我今年", 18, "岁")

# 自定义分隔符
print("2024", "01", "15", sep="-")

# 自定义结尾
print("第一部分", end=" -> ")
print("第二部分")

